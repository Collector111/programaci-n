package forejemplo;

public class forejemplo {
    public static void main(String[] args) {
        int num;
        System.out.println("Tabla de multiplicar del 4");
        for(num=1;num<=10;num++){
            System.out.println(4+" X "+ num+" = "+4*num);
        }

        num=0;
        while (num<=10) {
            System.out.println(4+" X "+ num+" = "+4*num);
            num++;
        }
    }
}
